#!/usr/bin/env python3
"""Decomp targets inside an asm file that hgify split (PR #6 and later).

hgify replaced some asm files with a run of objects in main.lsf: generated C
files (src/<base>_NN.c, "Generated by hgify/integrate.py") holding the
functions it matched, asm slices (asm/<base>_NN.s) holding the rest, and
asm/<base>_data.s. Some generated C files also keep functions as inline asm
("// FUNCTION <fn>: no matching C yet, the original asm"). The original
asm/<base>.s stays in the tree but is no longer linked, so it is not a target
itself; its units are:

  asm/<base>_NN.s   a linked slice: the usual workflow (write src/<base>_NN.c,
                    flip its main.lsf line)
  src/<base>_NN.c   a generated file with inline asm: rewrite those functions as
                    C in place (no main.lsf change)

Data-only slices (asm/<base>_data.s and slices without functions) are not
units: the generated C extern-references that data, so moving it is a change to
the whole split file, not a decomp of one piece.

See SPLIT_TARGETS.md for the workflow.

  split_units.py base   <path>        print asm/<base>.s if <path> is a split
                                      file or one of its pieces; exit 1 if not
  split_units.py units  asm/<base>.s  pending units in link order: not recorded
                                      completed/failed in progress.json; none
                                      left means the split file is done
  split_units.py funcs  <unit>        functions still in asm in that unit
  split_units.py pieces               every linked asm slice of every split file
"""

import json
import re
import sys
from pathlib import Path

import asmscan

ROOT = Path(__file__).resolve().parents[2]
HGIFY_MARK = "Generated by hgify/integrate.py"
INLINE_ASM_RE = re.compile(r"^// FUNCTION (\w+): no matching C", re.M)
FUNC_START_RE = re.compile(r"^\s*(?:thumb|arm)_func_start\s+(\w+)", re.M)
# Re-integrations rename a file's pieces: _NN/_data, then _rNN/_rdata, _sNN/_sdata, _tNN/_tdata, ...; a
# version-dependent function goes back to asm as a _vNN slice.
PIECE_RE = re.compile(r"^(.*)_([a-z]?\d{2,3}|[a-z]?data)$")


def lsf_objects():
    """main.lsf objects as "asm/<name>" / "src/<name>" (no .o), in link order."""
    return [f"{o['kind']}/{o['name']}" for o in asmscan.parse_lsf(ROOT)]


def recorded():
    """Files recorded completed or failed in progress.json (next_target.sh skips these too)."""
    path = Path(__file__).resolve().parent / "progress.json"
    if not path.exists():
        return set()
    data = json.loads(path.read_text())
    return {e["file"] if isinstance(e, dict) else e for e in data.get("completed", []) + data.get("failed", [])}


def is_generated(c_path):
    return c_path.exists() and HGIFY_MARK in c_path.read_text(errors="replace")


def pieces(base, objects=None):
    """Linked objects (without .o) of split file <base>, in link order; [] if it isn't split.
    <base> is the name under asm/ without .s, e.g. overlay_99. Pieces match by file name, so a
    C piece in a src/ subdirectory (src/field/overlay_01_021F3F50_00.c) counts too."""
    objects = lsf_objects() if objects is None else objects
    if f"asm/{base}" in objects or not (ROOT / "asm" / f"{base}.s").exists():
        return []
    found = []
    for o in objects:
        kind = o.partition("/")[0]
        m = PIECE_RE.match(o.rsplit("/", 1)[1])  # C pieces may sit in a src/ subdirectory
        if kind in ("asm", "src") and m and m.group(1) == base:
            found.append(o)
    if not any(o.startswith("src/") and is_generated(ROOT / f"{o}.c") for o in found):
        return []  # e.g. a hand-split file: not an hgify split
    return found


def base_of(path):
    """asm/<base>.s for a split file or one of its pieces, else None."""
    name = Path(path).stem
    objects = lsf_objects()
    if pieces(name, objects):
        return f"asm/{name}.s"
    m = PIECE_RE.match(name)
    if m and pieces(m.group(1), objects):
        return f"asm/{m.group(1)}.s"
    return None


def funcs(unit):
    """Functions still in asm in a unit (an asm slice or a generated C file)."""
    path = ROOT / unit
    if not path.exists():
        return []
    text = path.read_text(errors="replace")
    if unit.endswith(".s"):
        return FUNC_START_RE.findall(text)
    return INLINE_ASM_RE.findall(text) if HGIFY_MARK in text else []


def units(base_s):
    """Pending units of split file asm/<base>.s, in link order: slices with functions and
    generated C files with inline asm, minus those recorded in progress.json."""
    base = Path(base_s).stem
    done = recorded()
    out = []
    for o in pieces(base):
        unit = f"{o}.s" if o.startswith("asm/") else f"{o}.c"
        if unit not in done and funcs(unit):
            out.append(unit)
    return out


def all_pieces():
    """Every linked asm slice (asm/<name>.s) of every split file."""
    objects = lsf_objects()
    bases = set()
    for o in objects:
        m = PIECE_RE.match(o.rsplit("/", 1)[1])
        if m and m.group(1) not in bases and pieces(m.group(1), objects):
            bases.add(m.group(1))
    return [f"{o}.s" for b in sorted(bases) for o in pieces(b, objects) if o.startswith("asm/")]


def main(argv):
    if len(argv) == 2 and argv[1] == "pieces":
        print("\n".join(all_pieces()))
        return 0
    if len(argv) != 3 or argv[1] not in ("base", "units", "funcs"):
        sys.exit(__doc__)
    cmd, arg = argv[1], argv[2]
    if cmd == "base":
        b = base_of(arg)
        if not b:
            return 1
        print(b)
    elif cmd == "units":
        print("\n".join(units(arg)))
    else:
        print("\n".join(funcs(arg)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
