#!/usr/bin/env python3
"""Decomp targets inside an asm file that hgify split (PR #6 and later).

hgify replaced some asm files with a run of objects in main.lsf: generated C
files (src/<base>_NN.c, "Generated by hgify/integrate.py") holding the
functions it matched, asm slices (asm/<base>_NN.s) holding the rest, and
asm/<base>_data.s. Some generated C files also keep functions as inline asm
("// FUNCTION <fn>: no matching C yet, the original asm"). The original
asm/<base>.s stays in the tree but is no longer linked, so it is not a target
itself; its units are:

  asm/<base>_NN.s   a linked slice: the usual workflow (write src/<base>_NN.c,
                    flip its main.lsf line)
  src/<base>_NN.c   a generated file with inline asm: rewrite those functions as
                    C in place (no main.lsf change)

See SPLIT_TARGETS.md for the workflow.

  split_units.py base  <path>        print asm/<base>.s if <path> is a split
                                     file or one of its pieces; exit 1 if not
  split_units.py units asm/<base>.s  pending units, link order, data-only last
  split_units.py funcs <unit>        functions still in asm in that unit
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HGIFY_MARK = "Generated by hgify/integrate.py"
INLINE_ASM_RE = re.compile(r"^// FUNCTION (\w+): no matching C", re.M)
FUNC_START_RE = re.compile(r"^\s*(?:thumb|arm)_func_start\s+(\w+)", re.M)
PIECE_RE = re.compile(r"^(.*)_(\d{2,3}|data)$")


def lsf_objects():
    return re.findall(r"^\s*Object\s+(\S+)\.o\s*$", (ROOT / "main.lsf").read_text(), re.M)


def is_generated(c_path):
    return c_path.exists() and HGIFY_MARK in c_path.read_text(errors="replace")


def pieces(base, objects=None):
    """Linked objects (without .o) of split file <base>, in link order; [] if it isn't split.
    <base> is the name under asm/ without .s, e.g. overlay_99."""
    objects = lsf_objects() if objects is None else objects
    if f"asm/{base}" in objects or not (ROOT / "asm" / f"{base}.s").exists():
        return []
    found = []
    for o in objects:
        kind, _, name = o.partition("/")
        m = PIECE_RE.match(name)
        if kind in ("asm", "src") and m and m.group(1) == base:
            found.append(o)
    if not any(o.startswith("src/") and is_generated(ROOT / f"{o}.c") for o in found):
        return []  # e.g. a hand-split file: not an hgify split
    return found


def base_of(path):
    """asm/<base>.s for a split file or one of its pieces, else None."""
    p = Path(path)
    name = p.with_suffix("").as_posix().split("/", 1)[-1]
    objects = lsf_objects()
    if pieces(name, objects):
        return f"asm/{name}.s"
    m = PIECE_RE.match(name)
    if m and pieces(m.group(1), objects):
        return f"asm/{m.group(1)}.s"
    return None


def funcs(unit):
    """Functions still in asm in a unit (an asm slice or a generated C file)."""
    path = ROOT / unit
    if not path.exists():
        return []
    text = path.read_text(errors="replace")
    if unit.endswith(".s"):
        return FUNC_START_RE.findall(text)
    return INLINE_ASM_RE.findall(text) if HGIFY_MARK in text else []


def units(base_s):
    """Pending units of split file asm/<base>.s: slices and generated C files with
    inline asm, in link order, data-only slices last."""
    base = Path(base_s).stem
    code, data = [], []
    for o in pieces(base):
        if o.startswith("asm/"):
            unit = f"{o}.s"
            (code if funcs(unit) else data).append(unit)
        elif funcs(f"{o}.c"):
            code.append(f"{o}.c")
    return code + data


def main(argv):
    if len(argv) != 3 or argv[1] not in ("base", "units", "funcs"):
        sys.exit(__doc__)
    cmd, arg = argv[1], argv[2]
    if cmd == "base":
        b = base_of(arg)
        if not b:
            return 1
        print(b)
    elif cmd == "units":
        print("\n".join(units(arg)))
    else:
        print("\n".join(funcs(arg)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
