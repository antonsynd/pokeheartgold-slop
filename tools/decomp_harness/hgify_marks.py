"""How to recognise the C that hgify generated (PR #6 and later) and the pieces of the asm files it split.

One definition for coverage_ledger.py, split_units.py and tools/update_readme_progress.py, which all
count functions by these markers. A generated file starts with MARK and has one marker per function:

  // FUNCTION <fn>: matching C ...      the function is C (hgify's, or "(manual)" once someone rewrites it)
  // FUNCTION <fn>: no matching C ...   the function is still inline asm

A split asm file asm/<base>.s is linked as pieces named <base>_NN, with data in <base>_data. Each
re-integration renames them: _rNN/_rdata, then _sNN/_sdata, _tNN/_tdata, ...; a version-dependent
function goes back to asm as a _vNN slice. Match PIECE_RE against the file name only: C pieces live
in src/hgify/<base>/ (some in src/field/ or src/frontier/), asm slices in asm/. A hand-written file
can match too (src/overlay_06.c, src/scrcmd_12.c), so also check that asm/<base>.s exists.
"""

import re

MARK = "Generated by hgify/integrate.py"
C_FUNC_RE = re.compile(r"^// FUNCTION (\w+): matching C", re.M)
ASM_FUNC_RE = re.compile(r"^// FUNCTION (\w+): no matching C", re.M)
PIECE_RE = re.compile(r"^(.*)_([a-z]?\d{2,3}|[a-z]?data)$")
